#include <stdio.h>

int main() {
    int sum = 5 + 5;
    int subtraction = 5 - 5;
    int multiplication = 5 * 5;
    int division = 5 / 5;
    int modulo = 5 % 5;
    printf("Sum: %d\n", sum);
    printf("Subtraction: %d\n", subtraction);
    printf("Multiplication: %d\n", multiplication);
    printf("Division: %d\n", division);
    printf("Modulo: %d\n", modulo);
}
